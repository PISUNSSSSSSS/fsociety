-- ============================================================
-- fsociety: кланы и клан-теги
-- Запусти целиком в Supabase → SQL Editor → Run.
-- Скрипт можно запускать повторно: он ничего не удаляет.
--
-- Правила:
--  * у каждого игрока максимум один клан;
--  * тег клана 2–5 символов (латиница, кириллица, цифры), уникальный,
--    хранится заглавными буквами;
--  * роли в клане: owner (создатель), officer, member;
--  * вступление по коду приглашения, до 100 участников;
--  * админы сайта (admin, coowner, owner) могут удалить любой клан.
-- Таблицы закрыты RLS, всё работает только через функции ниже.
-- ============================================================

create table if not exists public.clans (
  id          bigint generated by default as identity primary key,
  tag         text not null unique,
  name        text not null,
  color       text not null default '#e5e5e5',
  description text not null default '',
  owner       uuid not null references public.profiles(id) on delete cascade,
  invite_code text not null unique,
  created_at  timestamptz not null default now(),
  constraint clans_tag_chk   check (tag ~ '^[A-Z0-9А-ЯЁ]{2,5}$'),
  constraint clans_name_chk  check (char_length(name) between 2 and 32),
  constraint clans_color_chk check (color ~ '^#[0-9a-fA-F]{6}$'),
  constraint clans_desc_chk  check (char_length(description) <= 300)
);

create table if not exists public.clan_members (
  user_id   uuid primary key references public.profiles(id) on delete cascade,
  clan_id   bigint not null references public.clans(id) on delete cascade,
  role      text not null default 'member',
  joined_at timestamptz not null default now(),
  constraint clan_members_role_chk check (role in ('owner', 'officer', 'member'))
);
create index if not exists clan_members_clan_idx on public.clan_members (clan_id);

alter table public.clans enable row level security;
alter table public.clan_members enable row level security;
revoke all on table public.clans, public.clan_members from anon, authenticated;

-- ---------- служебное ----------
create or replace function public.clan__site_rank(p_uid uuid)
returns int language sql stable security definer set search_path = public as $$
  select case coalesce((select p.role from public.profiles p where p.id = p_uid), 'user')
    when 'owner' then 5 when 'coowner' then 4 when 'admin' then 3
    when 'moderator' then 2 when 'sponsor' then 1 else 0 end;
$$;

create or replace function public.clan__new_code()
returns text language sql volatile set search_path = public as $$
  select upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 10));
$$;

create or replace function public.clan__norm_tag(p_tag text)
returns text language plpgsql immutable as $$
declare v text := upper(btrim(coalesce(p_tag, '')));
begin
  if v !~ '^[A-Z0-9А-ЯЁ]{2,5}$' then
    raise exception 'bad tag' using errcode = '22023';
  end if;
  return v;
end $$;

create or replace function public.clan__norm_color(p_color text)
returns text language sql immutable as $$
  select case when btrim(coalesce(p_color, '')) ~ '^#[0-9a-fA-F]{6}$'
              then lower(btrim(p_color)) else '#e5e5e5' end;
$$;

-- ---------- создать ----------
create or replace function public.clan_create(p_tag text, p_name text, p_color text default null, p_description text default '')
returns bigint language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid  uuid := auth.uid();
  v_tag  text;
  v_name text := btrim(coalesce(p_name, ''));
  v_id   bigint;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if exists (select 1 from public.clan_members m where m.user_id = v_uid) then
    raise exception 'already in clan' using errcode = '23505';
  end if;
  v_tag := public.clan__norm_tag(p_tag);
  if char_length(v_name) not between 2 and 32 then
    raise exception 'bad name' using errcode = '22023';
  end if;
  if exists (select 1 from public.clans c where c.tag = v_tag) then
    raise exception 'tag taken' using errcode = '23505';
  end if;
  begin
    insert into public.clans (tag, name, color, description, owner, invite_code)
    values (v_tag, v_name, public.clan__norm_color(p_color),
            left(btrim(coalesce(p_description, '')), 300), v_uid, public.clan__new_code())
    returning id into v_id;
  exception when unique_violation then
    raise exception 'tag taken' using errcode = '23505';
  end;
  insert into public.clan_members (user_id, clan_id, role) values (v_uid, v_id, 'owner');
  return v_id;
end $$;

-- ---------- информация ----------
create or replace function public.clan_get(p_clan bigint default null)
returns table (
  id bigint, tag text, name text, color text, description text,
  owner uuid, owner_nick text, created_at timestamptz,
  members int, my_role text, invite_code text
) language sql stable security definer set search_path = public as $$
  with me as (
    select m.clan_id, m.role from public.clan_members m where m.user_id = auth.uid()
  ), target as (
    select coalesce(p_clan, (select me.clan_id from me)) as cid
  )
  select c.id, c.tag, c.name, c.color, c.description,
         c.owner, op.nick, c.created_at,
         (select count(*)::int from public.clan_members x where x.clan_id = c.id),
         case when me.clan_id = c.id then me.role end,
         case when me.clan_id = c.id and me.role in ('owner', 'officer') then c.invite_code end
  from public.clans c
  join target on target.cid = c.id
  left join me on true
  left join public.profiles op on op.id = c.owner
  where auth.uid() is not null;
$$;

create or replace function public.clan_my()
returns table (
  id bigint, tag text, name text, color text, description text,
  owner uuid, owner_nick text, created_at timestamptz,
  members int, my_role text, invite_code text
) language sql stable security definer set search_path = public as $$
  select * from public.clan_get(null);
$$;

create or replace function public.clan_members(p_clan bigint)
returns table (user_id uuid, nick text, avatar text, user_role text, clan_role text, joined_at timestamptz)
language sql stable security definer set search_path = public as $$
  select m.user_id, p.nick, p.avatar, coalesce(p.role, 'user'), m.role, m.joined_at
  from public.clan_members m
  join public.profiles p on p.id = m.user_id
  where m.clan_id = p_clan and auth.uid() is not null
  order by case m.role when 'owner' then 0 when 'officer' then 1 else 2 end, m.joined_at
  limit 200;
$$;

create or replace function public.clan_list(p_search text default null, p_limit int default 50)
returns table (id bigint, tag text, name text, color text, description text, members int, created_at timestamptz)
language sql stable security definer set search_path = public as $$
  select c.id, c.tag, c.name, c.color, c.description,
         (select count(*)::int from public.clan_members x where x.clan_id = c.id) as members,
         c.created_at
  from public.clans c
  where auth.uid() is not null
    and (coalesce(btrim(p_search), '') = ''
         or c.tag ilike '%' || btrim(p_search) || '%'
         or c.name ilike '%' || btrim(p_search) || '%')
  order by members desc, c.created_at
  limit least(greatest(coalesce(p_limit, 50), 1), 100);
$$;

-- роль на сайте + клан-тег для списка игроков (ники в чате, форуме, личке)
create or replace function public.name_tags(p_ids uuid[])
returns table (user_id uuid, role text, clan_id bigint, clan_tag text, clan_color text, clan_name text)
language sql stable security definer set search_path = public as $$
  select p.id, coalesce(p.role, 'user'), c.id, c.tag, c.color, c.name
  from public.profiles p
  left join public.clan_members m on m.user_id = p.id
  left join public.clans c on c.id = m.clan_id
  where auth.uid() is not null
    and p.id = any (p_ids[1:200]);
$$;

-- ---------- вступить / выйти ----------
create or replace function public.clan_join(p_code text)
returns bigint language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_id  bigint;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if exists (select 1 from public.clan_members m where m.user_id = v_uid) then
    raise exception 'already in clan' using errcode = '23505';
  end if;
  select c.id into v_id from public.clans c
  where c.invite_code = upper(btrim(coalesce(p_code, '')));
  if v_id is null then raise exception 'bad code' using errcode = '22023'; end if;
  perform 1 from public.clans c where c.id = v_id for update;
  if (select count(*) from public.clan_members m where m.clan_id = v_id) >= 100 then
    raise exception 'clan full' using errcode = '22023';
  end if;
  begin
    insert into public.clan_members (user_id, clan_id, role) values (v_uid, v_id, 'member');
  exception when unique_violation then
    raise exception 'already in clan' using errcode = '23505';
  end;
  return v_id;
end $$;

create or replace function public.clan_leave()
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_me  public.clan_members%rowtype;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into v_me from public.clan_members m where m.user_id = v_uid;
  if not found then raise exception 'not in clan' using errcode = '22023'; end if;
  if v_me.role = 'owner' then
    if exists (select 1 from public.clan_members m where m.clan_id = v_me.clan_id and m.user_id <> v_uid) then
      raise exception 'owner must transfer' using errcode = '22023';
    end if;
    delete from public.clans c where c.id = v_me.clan_id;
  else
    delete from public.clan_members m where m.user_id = v_uid;
  end if;
end $$;

-- ---------- управление ----------
create or replace function public.clan_kick(p_user uuid)
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_me  public.clan_members%rowtype;
  v_t   public.clan_members%rowtype;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into v_me from public.clan_members m where m.user_id = v_uid;
  select * into v_t  from public.clan_members m where m.user_id = p_user;
  if v_me.user_id is null or v_t.user_id is null or v_me.clan_id <> v_t.clan_id or p_user = v_uid then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if not (v_me.role = 'owner' or (v_me.role = 'officer' and v_t.role = 'member')) then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  delete from public.clan_members m where m.user_id = p_user;
end $$;

-- p_role: 'officer' | 'member' | 'owner' (передать клан)
create or replace function public.clan_set_role(p_user uuid, p_role text)
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_me  public.clan_members%rowtype;
  v_t   public.clan_members%rowtype;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  if p_role not in ('officer', 'member', 'owner') then raise exception 'bad role' using errcode = '22023'; end if;
  select * into v_me from public.clan_members m where m.user_id = v_uid;
  select * into v_t  from public.clan_members m where m.user_id = p_user;
  if v_me.role is distinct from 'owner' or v_t.user_id is null
     or v_me.clan_id <> v_t.clan_id or p_user = v_uid then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  if p_role = 'owner' then
    update public.clan_members m set role = 'officer' where m.user_id = v_uid;
    update public.clan_members m set role = 'owner' where m.user_id = p_user;
    update public.clans c set owner = p_user where c.id = v_me.clan_id;
  else
    update public.clan_members m set role = p_role where m.user_id = p_user;
  end if;
end $$;

create or replace function public.clan_update(p_tag text, p_name text, p_color text, p_description text)
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid  uuid := auth.uid();
  v_me   public.clan_members%rowtype;
  v_tag  text;
  v_name text := btrim(coalesce(p_name, ''));
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into v_me from public.clan_members m where m.user_id = v_uid;
  if v_me.role is distinct from 'owner' then raise exception 'not allowed' using errcode = '42501'; end if;
  v_tag := public.clan__norm_tag(p_tag);
  if char_length(v_name) not between 2 and 32 then
    raise exception 'bad name' using errcode = '22023';
  end if;
  if exists (select 1 from public.clans c where c.tag = v_tag and c.id <> v_me.clan_id) then
    raise exception 'tag taken' using errcode = '23505';
  end if;
  begin
    update public.clans c
       set tag = v_tag, name = v_name, color = public.clan__norm_color(p_color),
           description = left(btrim(coalesce(p_description, '')), 300)
     where c.id = v_me.clan_id;
  exception when unique_violation then
    raise exception 'tag taken' using errcode = '23505';
  end;
end $$;

create or replace function public.clan_regen_invite()
returns text language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid  uuid := auth.uid();
  v_me   public.clan_members%rowtype;
  v_code text := public.clan__new_code();
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into v_me from public.clan_members m where m.user_id = v_uid;
  if v_me.role is null or v_me.role not in ('owner', 'officer') then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  update public.clans c set invite_code = v_code where c.id = v_me.clan_id;
  return v_code;
end $$;

-- распустить свой клан (владелец) или удалить любой клан (админ сайта)
create or replace function public.clan_delete(p_clan bigint default null)
returns void language plpgsql volatile security definer set search_path = public as $$
declare
  v_uid uuid := auth.uid();
  v_me  public.clan_members%rowtype;
  v_id  bigint;
begin
  if v_uid is null then raise exception 'not authenticated' using errcode = '28000'; end if;
  select * into v_me from public.clan_members m where m.user_id = v_uid;
  v_id := coalesce(p_clan, v_me.clan_id);
  if v_id is null then raise exception 'not in clan' using errcode = '22023'; end if;
  if not coalesce(v_me.clan_id = v_id and v_me.role = 'owner', false)
     and public.clan__site_rank(v_uid) < 3 then
    raise exception 'not allowed' using errcode = '42501';
  end if;
  delete from public.clans c where c.id = v_id;
end $$;

-- ---------- доступ ----------
revoke all on function public.clan__site_rank(uuid) from public, anon, authenticated;
revoke all on function public.clan__new_code() from public, anon, authenticated;
revoke all on function public.clan__norm_tag(text) from public, anon, authenticated;
revoke all on function public.clan__norm_color(text) from public, anon, authenticated;

do $$
declare f text;
begin
  foreach f in array array[
    'clan_create(text,text,text,text)', 'clan_get(bigint)', 'clan_my()',
    'clan_members(bigint)', 'clan_list(text,int)', 'name_tags(uuid[])',
    'clan_join(text)', 'clan_leave()', 'clan_kick(uuid)', 'clan_set_role(uuid,text)',
    'clan_update(text,text,text,text)', 'clan_regen_invite()', 'clan_delete(bigint)'
  ] loop
    execute format('revoke all on function public.%s from public, anon', f);
    execute format('grant execute on function public.%s to authenticated', f);
  end loop;
end $$;

